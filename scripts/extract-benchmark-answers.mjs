// Extracts the verbatim WITHOUT/WITH answers per task from
// docs/comparisons/COMP_ANTIGRAVITY.md into website/src/data/benchmarkAnswers.ts.
// Run from website/: npm run extract:answers  (regenerate after re-running the benchmark)
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const docPath = join(here, '..', '..', 'docs', 'comparisons', 'COMP_ANTIGRAVITY.md')
const outPath = join(here, '..', 'src', 'data', 'benchmarkAnswers.ts')

const lines = readFileSync(docPath, 'utf8').split(/\r?\n/)

// '### 1. service_architecture — "Explain…"' (answers contain their own internal
// headings, but those never match lowercase_snake task names).
const TASK = /^### (\d+)\. ([a-z_]+) /
// The arm headers vary per task ("the answer", "the impact list", "the fix…",
// "the verdict", "the file list") but the circle emoji is stable — and matching
// on "WITH" alone would also hit "WITHOUT".
const WITHOUT = /^#### .*🔴/
const WITH = /^#### .*🟢/
const SCORE = /^\*Verbatim .*\bscore (\d+)\/100/
const JUDGEMENT = /^\*\*.*Which is better\?\*\*/
const TRANSCRIPTS = /^\*\*Transcripts:\*\*/

function newTask() {
  return { number: 0, task: '', arm: null, buffers: { without: [], with: [] }, scores: { without: null, with: null } }
}

const tasks = []
let current = null

for (const line of lines) {
  const taskMatch = TASK.exec(line)
  if (taskMatch) {
    current = newTask()
    current.number = Number(taskMatch[1])
    current.task = taskMatch[2]
    tasks.push(current)
    continue
  }
  if (!current) continue

  if (WITHOUT.test(line) || WITH.test(line)) {
    current.arm = WITHOUT.test(line) ? 'without' : 'with'
    continue
  }
  if (JUDGEMENT.test(line)) {
    current.arm = null // judgement + transcripts follow; stop collecting
    continue
  }
  if (current.arm) {
    const scoreMatch = SCORE.exec(line)
    if (scoreMatch) {
      current.scores[current.arm] = Number(scoreMatch[1])
      continue
    }
    if (TRANSCRIPTS.test(line)) {
      current.arm = null
      continue
    }
    current.buffers[current.arm].push(line.replace(/^> ?/, ''))
  }
}

function tidy(block) {
  const clone = [...block]
  while (clone.length && (/^(---|\s*)$/.test(clone[clone.length - 1]))) clone.pop()
  while (clone.length && (/^(---|\s*)$/.test(clone[0]))) clone.shift()
  return clone.join('\n').trim()
}

const result = {}
for (const { task, buffers, scores } of tasks) {
  const without = tidy(buffers.without)
  const withText = tidy(buffers.with)
  if (!without) {
    console.error(`! ${task}: empty WITHOUT answer, skipping`)
    continue
  }
  result[task] = {
    withoutScore: scores.without,
    withScore: scores.with,
    without,
    with: withText,
  }
  console.log(`✓ ${task}: without ${without.length} chars (score ${scores.without}), with ${withText.length} chars (score ${scores.with})`)
}

const entries = Object.entries(result)
  .map(([task, v]) => [
    `  '${task}': {`,
    `    withoutScore: ${v.withoutScore},`,
    `    withScore: ${v.withScore},`,
    `    without: ${JSON.stringify(v.without)},`,
    `    with: ${JSON.stringify(v.with)},`,
    `  },`,
  ].join('\n'))
  .join('\n')

const file = `// AUTO-GENERATED by website/scripts/extract-benchmark-answers.mjs — do not edit by hand.\n// Source: docs/comparisons/COMP_ANTIGRAVITY.md — verbatim agent answers per benchmark task.\n// Regenerate with: cd website && npm run extract:answers\n\nexport type BenchmarkAnswerPair = {\n  withoutScore: number | null\n  withScore: number | null\n  without: string\n  with: string\n}\n\nexport const benchmarkAnswers: Record<string, BenchmarkAnswerPair> = {\n${entries}\n}\n`

writeFileSync(outPath, file)
console.log(`\nWrote ${outPath} (${Object.keys(result).length} tasks)`)
